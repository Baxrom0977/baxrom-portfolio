const languageButtons = document.querySelectorAll(".language__button");

function changeLanguage(language) {
  const elements = document.querySelectorAll("[data-i18n]");

  elements.forEach((element) => {
    const key = element.dataset.i18n;

    const text = translations[language]?.[key];

    if (text !== undefined) {
      element.textContent = text;
    }
  });

  // Translate only the direct text node, preserving nested arrows and styled spans.
  document.querySelectorAll("[data-i18n-text]").forEach((element) => {
    const text = translations[language]?.[element.dataset.i18nText];
    const node = [...element.childNodes].find(
      (node) => node.nodeType === Node.TEXT_NODE && node.textContent.trim(),
    );
    if (text !== undefined && node) node.textContent = text + " ";
  });
  for (const attribute of ["aria-label", "alt", "content", "placeholder"]) {
    document
      .querySelectorAll("[data-i18n-" + attribute + "]")
      .forEach((element) => {
        const text =
          translations[language]?.[
            element.getAttribute("data-i18n-" + attribute)
          ];
        if (text !== undefined) element.setAttribute(attribute, text);
      });
  }
  document.documentElement.lang = language;
  syncTranslatedMenuLabel();

  languageButtons.forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === language);
  });
  localStorage.setItem("language", language);
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const language = button.dataset.lang;

    changeLanguage(language);
  });
});

function syncTranslatedMenuLabel() {
  const button = document.querySelector("#menu-toggle[data-i18n-aria-label]");
  if (!button) return;
  const open =
    document.querySelector(".nav")?.classList.contains("active") || false;
  const language = document.documentElement.lang;
  button.setAttribute(
    "aria-label",
    translations[language]?.[open ? "common.closeMenu" : "common.openMenu"] ||
      "Open menu",
  );
  button.setAttribute("aria-expanded", String(open));
}
// Keep the translated label in sync with menu changes made by app.js.
const translatedMenu = document.querySelector(".nav");
if (
  translatedMenu &&
  document.querySelector("#menu-toggle[data-i18n-aria-label]")
) {
  new MutationObserver(syncTranslatedMenuLabel).observe(translatedMenu, {
    attributes: true,
    attributeFilter: ["class"],
  });
}
